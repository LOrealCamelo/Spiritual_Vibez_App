"""Opt-in real PostgreSQL verification uses disposable, uniquely named schemas."""
import os
import uuid
import pytest

if os.getenv('DATABASE_URL'):
    raise pytest.UsageError('Refusing tests with DATABASE_URL set. Unset it; use POSTGRES_TEST_URL for isolated cloud verification.')


@pytest.fixture(autouse=True)
def isolated_postgres_verification(monkeypatch):
    url=os.getenv('POSTGRES_TEST_URL')
    if not url:
        yield
        return
    prefix='sv_verify_'+uuid.uuid4().hex[:12]
    monkeypatch.setenv('DATABASE_URL',url)
    monkeypatch.setenv('DATABASE_URL_UNPOOLED',os.getenv('POSTGRES_TEST_URL_UNPOOLED',url))
    monkeypatch.setenv('DATABASE_NAMESPACE',prefix)
    yield
    # Delete only schemas generated by this test, never app or pre-existing schemas.
    import psycopg
    from psycopg import sql
    with psycopg.connect(os.getenv('POSTGRES_TEST_URL_UNPOOLED',url)) as conn:
        rows=conn.execute("SELECT schema_name FROM information_schema.schemata WHERE schema_name LIKE %s",(prefix+'_%',)).fetchall()
        for (name,) in rows:
            if name.startswith(prefix+'_'):
                conn.execute(sql.SQL('DROP SCHEMA {} CASCADE').format(sql.Identifier(name)))
